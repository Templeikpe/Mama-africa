const AVAILABLE_LANGS = Object.keys(i18n);

function safeGetStoredLang(){
  try{ return localStorage.getItem('mama_lang'); }catch(e){ return null; }
}
function safeSetStoredLang(lang){
  try{ localStorage.setItem('mama_lang', lang); }catch(e){ /* storage blocked (file://, private mode…) — URL param below still works */ }
}
function getInitialLang(){
  try{
    const urlLang = new URLSearchParams(window.location.search).get('lang');
    if(urlLang && AVAILABLE_LANGS.includes(urlLang)) return urlLang;
  }catch(e){}
  const stored = safeGetStoredLang();
  if(stored && AVAILABLE_LANGS.includes(stored)) return stored;
  return 'en';
}

// Réécrit tous les liens internes (menu, footer, boutons…) pour qu'ils transportent
// la langue active dans l'URL (?lang=xx) — ainsi la langue reste correcte même si
// le stockage local est bloqué ou différent d'une page à l'autre.
function syncLinkLang(lang){
  document.querySelectorAll('a[href]').forEach(a=>{
    const raw = a.getAttribute('href');
    if(!raw || raw.startsWith('#') || raw.startsWith('mailto:') || raw.startsWith('tel:') || raw.startsWith('http')) return;
    if(!raw.includes('.html')) return;
    try{
      const url = new URL(raw, window.location.href);
      if(url.origin !== window.location.origin) return;
      url.searchParams.set('lang', lang);
      a.setAttribute('href', url.pathname + url.search + url.hash);
    }catch(e){}
  });
}

let currentLang = getInitialLang();

function goHome(){
  window.location.href = 'index.html?lang=' + currentLang;
}

function applyLang(lang){
  currentLang = lang;
  safeSetStoredLang(lang);
  const t = i18n[lang];
  if (!t) return;
  document.documentElement.lang = lang;
  document.documentElement.dir = 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(t[key]) el.innerHTML = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el=>{
    const key = el.getAttribute('data-i18n-placeholder');
    if(t[key]) el.placeholder = t[key];
  });
  document.querySelectorAll('.lang-btn').forEach(btn=>{
    btn.classList.toggle('active', btn.dataset.lang===lang);
  });
  syncLinkLang(lang);
  const suc = document.getElementById('formSuccess');
  if(suc) suc.style.display='none';
  // update form note
  const noteEl = document.getElementById('formNoteText');
  if(noteEl && formNoteMsg[lang]) noteEl.innerHTML = formNoteMsg[lang];
}


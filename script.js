const corridorPoints = {
  korhogo:{coords:[9.4578,-5.6296]},
  yamoussoukro:{coords:[6.8206,-5.2767]},
  abidjan:{coords:[5.3600,-4.0083]},
  rotterdam:{coords:[51.9244,4.4777]}
};
let corridorMarkers = {};

function corridorBezier(p0,p1,p2,n){
  const pts=[];
  for(let i=0;i<=n;i++){
    const t=i/n;
    const lat=(1-t)*(1-t)*p0[0]+2*(1-t)*t*p1[0]+t*t*p2[0];
    const lng=(1-t)*(1-t)*p0[1]+2*(1-t)*t*p1[1]+t*t*p2[1];
    pts.push([lat,lng]);
  }
  return pts;
}

function corridorPopupHTML(key){
  const t = i18n[currentLang] || i18n.fr;
  const title = t['corr_'+key+'_title'] || key;
  const text = t['corr_'+key+'_text'] || '';
  return '<div class="corridor-popup-title">'+title+'</div><p class="corridor-popup-text">'+text+'</p>';
}

function initCorridorMap(){
  const el = document.getElementById('corridorLeafletMap');
  if(!el || typeof L === 'undefined') return;
  el.innerHTML = '';

  const map = L.map(el,{zoomControl:true,scrollWheelZoom:false,minZoom:2});
  L.tileLayer('https://{s}.basemaps.cartocdn.com/dark_all/{z}/{x}/{y}{r}.png',{
    attribution:'&copy; <a href="https://www.openstreetmap.org/copyright" target="_blank" rel="noopener">OpenStreetMap</a> contributors &copy; <a href="https://carto.com/attributions" target="_blank" rel="noopener">CARTO</a>',
    subdomains:'abcd',
    maxZoom:19
  }).addTo(map);

  /* internal collection network feeding the port */
  L.polyline([corridorPoints.korhogo.coords, corridorPoints.abidjan.coords],{color:'#D4A373',weight:1.5,opacity:0.5,dashArray:'2 8'}).addTo(map);
  L.polyline([corridorPoints.yamoussoukro.coords, corridorPoints.abidjan.coords],{color:'#D4A373',weight:1.5,opacity:0.5,dashArray:'2 8'}).addTo(map);

  /* maritime corridor Abidjan -> Rotterdam, bulging into the Atlantic */
  const seaRoute = corridorBezier(corridorPoints.abidjan.coords,[24,-20],corridorPoints.rotterdam.coords,60);
  L.polyline(seaRoute,{color:'#D4A373',weight:2.5,opacity:0.85,dashArray:'1 10'}).addTo(map);

  Object.keys(corridorPoints).forEach(key=>{
    const isRotterdam = key==='rotterdam';
    const icon = L.divIcon({
      className:'',
      html:'<div class="corridor-pin'+(isRotterdam?' rotterdam':'')+'"><span class="corridor-pin-pulse"></span><span class="corridor-pin-dot"></span></div>',
      iconSize:[16,16],
      iconAnchor:[8,8],
      popupAnchor:[0,-8]
    });
    const marker = L.marker(corridorPoints[key].coords,{icon:icon}).addTo(map);
    marker.bindPopup(corridorPopupHTML(key));
    corridorMarkers[key] = marker;
  });

  const bounds = L.latLngBounds(Object.values(corridorPoints).map(p=>p.coords));
  map.fitBounds(bounds,{padding:[40,40]});
}

function updateCorridorMapLang(){
  Object.keys(corridorMarkers).forEach(key=>{
    corridorMarkers[key].setPopupContent(corridorPopupHTML(key));
  });
}

if(document.getElementById('corridorLeafletMap')){
  initCorridorMap();
}

const _origApplyLang = applyLang;
applyLang = function(lang){
  _origApplyLang(lang);
  if(Object.keys(corridorMarkers).length) updateCorridorMapLang();
};


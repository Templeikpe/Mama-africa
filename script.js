function acceptCookies() {
  localStorage.setItem('mama_cookies', 'accepted');
  document.getElementById('cookie-banner').style.transform = 'translateY(100%)';
}
function refuseCookies() {
  localStorage.setItem('mama_cookies', 'refused');
  document.getElementById('cookie-banner').style.transform = 'translateY(100%)';
}
function resetCookies() {
  localStorage.removeItem('mama_cookies');
  closeLegal();
  setTimeout(() => document.getElementById('cookie-banner').classList.add('show'), 300);
}
// Show cookie banner if no choice made
window.addEventListener('load', () => {
  if (!localStorage.getItem('mama_cookies')) {
    setTimeout(() => document.getElementById('cookie-banner').classList.add('show'), 2500);
  }
});